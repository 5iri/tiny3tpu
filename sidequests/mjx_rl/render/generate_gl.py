"""Generate a checked GLAD-to-TinyGL dispatch table (no dynamic loader)."""
from pathlib import Path
import re
ROOT=Path(__file__).resolve().parents[3]

def generate(out):
    mj=ROOT/'third_party/mujoco_renderer/src/render/classic'
    glad=(mj/'glad/glad.h').read_text()
    tiny=(ROOT/'third_party/tinygl/include/TGL/gl.h').read_text()
    tiny=re.sub(r'#if 0.*?#endif','',tiny,flags=re.S)
    available=set(re.findall(r'\b(gl\w+)\s*\(',tiny))
    used=set(re.findall(r'\b(gl[A-Z]\w+)\s*\(', '\n'.join(p.read_text() for p in mj.glob('*.c'))))
    types={k:(r,a) for r,k,a in re.findall(r'typedef (.*?) \(APIENTRYP (PFNGL\w+PROC)\)\((.*?)\);',glad)}
    symbols=dict(re.findall(r'GLAPI (PFNGL\w+PROC) (mjGlad_gl\w+);',glad))
    custom={'glEnable','glDisable','glDepthFunc','glDepthRange','glAlphaFunc','glClearStencil',
            'glTexCoord2d','glScissor','glLineWidth','glFogfv','glBindFramebuffer','glOrtho','glFinish'}
    body=['/* Generated by generate_gl.py; unsupported operations abort. */',
          '#include "render/classic/glad/glad.h"', '#include "port.h"']
    for flag in re.findall(r'GLAPI int (mjGLAD_\w+);',glad):body.append(f'int {flag}=0;')
    body.append('int mjGladLoadGL(void) { port_fail("dynamic GL loading is unavailable"); return 0; }')
    for typ,symbol in symbols.items():
        name=symbol.removeprefix('mjGlad_')
        if name not in used:continue
        result,args=types[typ]
        if name in custom:
            target='port_'+name;body.append(f'extern {result} {target}({args});')
        elif name in available:
            target='t'+name;body.append(f'extern {result} {target}({args});')
        else:
            target='unsupported_'+name
            body.append(f'static {result} {target}({args}) {{ port_fail("{name}");'+(' return 0;' if result!='void' else '')+' }')
        body.append(f'{typ} {symbol} = {target};')
    (out/'gl_dispatch.c').write_text('\n'.join(body)+'\n')
